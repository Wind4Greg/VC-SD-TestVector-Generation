/*
    BBS proof values for the bbs-2023 cryptosuite and its features.

    Reference: https://w3c.github.io/vc-di-bbs/

    featureOption is one of "baseline", "anonymous_holder_binding",
    "pseudonym", or "holder_binding_pseudonym". The feature determines the
    header byte and which extra components follow the baseline ones:

      base proof:    baseline components + signerNymEntropy (pseudonym features)
      derived proof: baseline components + pseudonym (pseudonym features)
                     + lengthBBSMessages (all non-baseline features)
*/
import { compressShuffledLabelMap } from '../lib/labelMaps.js'
import {
  serializeProofValue, parseProofValue, checkBytes, checkIntegerArray,
  checkCompressedLabelMap
} from '../lib/proofValue.js'

// Header bytes (third byte) as currently generated by the scripts here.
// NOTE: "pseudonym" and "holder_binding_pseudonym" currently share 0x08/0x09.
const FEATURES = {
  baseline: { base: 0x02, derived: 0x03, nym: false },
  anonymous_holder_binding: { base: 0x04, derived: 0x05, nym: false },
  pseudonym: { base: 0x08, derived: 0x09, nym: true },
  holder_binding_pseudonym: { base: 0x08, derived: 0x09, nym: true }
}

function feature (featureOption) {
  const f = FEATURES[featureOption]
  if (!f) {
    throw new Error(`Unknown BBS featureOption: ${featureOption}`)
  }
  return f
}

/*
  serializeBaseProofValue: header bytes 0xd9, 0x5d, <feature base byte>
  followed by the CBOR encoding of [bbsSignature, bbsHeader, publicKey,
  hmacKey, mandatoryPointers] and, for the pseudonym features,
  signerNymEntropy.
*/
export function serializeBaseProofValue ({
  bbsSignature, bbsHeader, publicKey, hmacKey, mandatoryPointers,
  signerNymEntropy, featureOption = 'baseline'
}) {
  const f = feature(featureOption)
  const components = [bbsSignature, bbsHeader, publicKey, hmacKey, mandatoryPointers]
  if (f.nym) {
    components.push(signerNymEntropy)
  }
  return serializeProofValue(f.base, components)
}

/*
  parseBaseProofValue: check the header bytes and component count for the
  feature, CBOR-decode and return the named components.
*/
export function parseBaseProofValue (proofValue, featureOption = 'baseline') {
  const f = feature(featureOption)
  const [bbsSignature, bbsHeader, publicKey, hmacKey, mandatoryPointers, signerNymEntropy] =
    parseProofValue(proofValue, f.base, f.nym ? 6 : 5)
  const result = { bbsSignature, bbsHeader, publicKey, hmacKey, mandatoryPointers }
  if (f.nym) {
    result.signerNymEntropy = signerNymEntropy
  }
  return result
}

/*
  serializeDerivedProofValue: header bytes 0xd9, 0x5d, <feature derived byte>
  followed by the CBOR encoding of [bbsProof, compressedLabelMap,
  mandatoryIndexes, selectiveIndexes, presentationHeader], then pseudonym (for
  the pseudonym features) and lengthBBSMessages (for all non-baseline
  features).
*/
export function serializeDerivedProofValue ({
  bbsProof, labelMap, mandatoryIndexes, selectiveIndexes, presentationHeader,
  pseudonym, lengthBBSMessages, featureOption = 'baseline'
}) {
  const f = feature(featureOption)
  const components = [bbsProof, compressShuffledLabelMap(labelMap), mandatoryIndexes,
    selectiveIndexes, presentationHeader]
  if (f.nym) {
    components.push(pseudonym)
  }
  if (featureOption !== 'baseline') {
    components.push(lengthBBSMessages)
  }
  return serializeProofValue(f.derived, components)
}

/*
  parseDerivedProofValue: check the header bytes and component count for the
  feature, CBOR-decode, check the label map (integers to integers) and the
  indexes, and return the named components. The label map is returned in its
  compressed form.
*/
export function parseDerivedProofValue (proofValue, featureOption = 'baseline') {
  const f = feature(featureOption)
  const extra = (f.nym ? 1 : 0) + (featureOption !== 'baseline' ? 1 : 0)
  const components = parseProofValue(proofValue, f.derived, 5 + extra)
  const [bbsProof, compressedLabelMap, mandatoryIndexes, selectiveIndexes, presentationHeader] = components
  checkBytes(bbsProof, 'bbsProof')
  checkCompressedLabelMap(compressedLabelMap, Number.isInteger)
  checkIntegerArray(mandatoryIndexes, 'mandatory indexes')
  checkIntegerArray(selectiveIndexes, 'selective indexes')
  checkBytes(presentationHeader, 'presentationHeader')
  const result = { bbsProof, compressedLabelMap, mandatoryIndexes, selectiveIndexes, presentationHeader }
  let i = 5
  if (f.nym) {
    result.pseudonym = components[i++]
    checkBytes(result.pseudonym, 'pseudonym')
  }
  if (featureOption !== 'baseline') {
    result.lengthBBSMessages = components[i]
    if (!Number.isInteger(result.lengthBBSMessages)) {
      throw new Error('Bad lengthBBSMessages in proofValue')
    }
  }
  return result
}
